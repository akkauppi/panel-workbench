import { copyFile, lstat, mkdir, mkdtemp, readFile, rename, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const destination = join(root, 'dist/panel-workbench');
const marker = '.panel-workbench-public-build';
// Explicit production inputs: private models, saved studies, tests, and Git
// history cannot enter the distributable through a recursive repository copy.
const files = [
  'server.mjs',
  'demo/index.html', 'demo/style.css', 'demo/app.js', 'demo/examples.js', 'demo/local-examples.js',
  'demo/io.js', 'demo/geometry.js', 'demo/fitted.js', 'demo/solids.js', 'demo/rendering.js',
  'demo/assembly-guides.js', 'demo/explode.js', 'demo/panel-offsets.js', 'demo/panel-diagnostics.js', 'demo/generator-policy.js', 'demo/curvature-sizing.js', 'demo/local-save-preference.js', 'demo/project-document.js', 'demo/project-feedback.js', 'demo/project-recovery.js', 'demo/project-ui.js',
  'demo/carving.js', 'demo/corner-drag.js', 'demo/study.js', 'demo/design.js',
  'demo/layout.js', 'demo/layout-edit.js', 'demo/pattern.js', 'demo/structured.js', 'demo/regularized.js', 'demo/quality.js', 'demo/worker.js',
  'demo/laser-net.js', 'demo/laser-export.js', 'demo/laser-ui.js', 'demo/laser-worker.js',
  'demo/rhino-runtime.js', 'demo/rhino-export.js', 'demo/rhino-import.js', 'demo/rhino-worker.js', 'demo/rhino-format.js',
  'demo/vendor/rhino3dm/rhino3dm.module.js', 'demo/vendor/rhino3dm/rhino3dm.wasm',
  'demo/vendor/rhino3dm/LICENSE.txt', 'demo/vendor/rhino3dm/NOTICE.txt',
  'demo/vendor/THREE-LICENSE.txt', 'demo/vendor/three.core.js',
  'demo/vendor/three.module.js', 'demo/vendor/addons/controls/OrbitControls.js',
];

await mkdir(join(root, 'dist'), { recursive: true });
const temporary = await mkdtemp(join(root, 'dist/.public-build-'));
try {
  for (const relative of files) {
    const source = join(root, relative), target = join(temporary, relative);
    const info = await lstat(source);
    if (!info.isFile() || info.isSymbolicLink()) throw new Error(`Expected a regular distribution file: ${relative}`);
    await mkdir(dirname(target), { recursive: true });
    await copyFile(source, target);
  }
  await writeFile(join(temporary, 'package.json'), JSON.stringify({ name: 'panel-workbench', private: true, type: 'module', scripts: { start: 'node server.mjs' } }, null, 2) + '\n');
  await writeFile(join(temporary, 'README.md'), '# Panel Workbench\n\nRun `npm start` and open http://localhost:8787. The `demo/` directory can also be served as a static site.\n\nExamples are generated from analytic surfaces by this project. No private or third-party mesh assets are included. Library licenses are in `demo/vendor/THREE-LICENSE.txt` and `demo/vendor/rhino3dm/LICENSE.txt`.\n');
  await writeFile(join(temporary, marker), 'Generated by scripts/build-public.mjs\n');
  const existing = await lstat(destination).catch(error => { if (error.code !== 'ENOENT') throw error; return null; });
  if (existing) {
    if (!existing.isDirectory() || existing.isSymbolicLink() || await readFile(join(destination, marker), 'utf8').catch(() => '') !== 'Generated by scripts/build-public.mjs\n') {
      throw new Error('The public-build destination contains an unrelated directory. Move it before rebuilding.');
    }
    await rm(destination, { recursive: true });
  }
  await rename(temporary, destination);
  console.log(`Public build: ${destination}\n${files.length} production files; no model assets or Git history.`);
} catch (error) {
  await rm(temporary, { recursive: true, force: true });
  throw error;
}
