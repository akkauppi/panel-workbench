import { execFileSync } from 'node:child_process';
import { cp, lstat, mkdir, mkdtemp, readFile, rename, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const destination = join(root, 'dist/panel-workbench-pages');
const marker = '.panel-workbench-pages-build';
const signature = 'Generated by scripts/build-pages.mjs\n';

// Reuse the reviewed production allowlist, never the repository or its history.
execFileSync(process.execPath, [join(root, 'scripts/build-public.mjs')], { stdio: 'inherit' });
await mkdir(join(root, 'dist'), { recursive: true });
const temporary = await mkdtemp(join(root, 'dist/.pages-build-'));
try {
  await cp(join(root, 'dist/panel-workbench/demo'), temporary, { recursive: true });
  await writeFile(join(temporary, '.nojekyll'), '');
  await writeFile(join(temporary, marker), signature);
  const existing = await lstat(destination).catch(error => {
    if (error.code !== 'ENOENT') throw error;
    return null;
  });
  if (existing) {
    if (!existing.isDirectory() || existing.isSymbolicLink() ||
        await readFile(join(destination, marker), 'utf8').catch(() => '') !== signature) {
      throw new Error('The Pages destination contains an unrelated directory. Move it before rebuilding.');
    }
    await rm(destination, { recursive: true });
  }
  await rename(temporary, destination);
  console.log(`GitHub Pages files: ${destination}\nPublish this directory at the site root. No Node server is needed on the host.`);
} catch (error) {
  await rm(temporary, { recursive: true, force: true });
  throw error;
}
