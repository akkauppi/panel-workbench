import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { lstat, mkdir, mkdtemp, readFile, readdir, rename, rm, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const destination = join(root, 'dist/panel-workbench-pages');
const marker = '.panel-workbench-pages-build';
const signature = 'Generated by scripts/build-pages.mjs\n';
const epoch = process.env.SOURCE_DATE_EPOCH;
if (epoch !== undefined && (!/^\d+$/.test(epoch) || !Number.isSafeInteger(Number(epoch)))) {
  throw new Error('SOURCE_DATE_EPOCH must be an integer Unix timestamp in seconds.');
}
const builtAt = new Date(epoch === undefined ? Date.now() : Number(epoch) * 1000);
if (!Number.isFinite(builtAt.getTime())) throw new Error('The build timestamp is outside the supported range.');
const buildLabel = `Build ${builtAt.toISOString().replace('T', ' ').replace(/\.\d{3}Z$/, ' UTC')}`;

async function collect(directory, prefix = '') {
  const files = [];
  for (const entry of (await readdir(directory, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name, 'en'))) {
    const relative = prefix + entry.name, path = join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await collect(path, `${relative}/`));
    else if (entry.isFile()) files.push({ relative, contents: await readFile(path) });
    else throw new Error(`Expected a regular production file: ${relative}`);
  }
  return files;
}

function versionWorkers(source) {
  // A string Worker URL resolves against the document, unlike module imports.
  // Resolve it from the emitted module so its dependency graph stays in the
  // same release directory. This is a build transform; local serving is intact.
  return source.replace(/\bnew\s+Worker\(\s*(['"])(\.\.?\/[^'"]+)\1/g,
    (_, quote, path) => `new Worker(new URL(${quote}${path}${quote}, import.meta.url)`);
}

function versionIndex(source, release) {
  const prefix = `./assets/${release}/`;
  let html = source.replace(/(<(?:link|script)\b[^>]*\b(?:href|src)=)(['"])(\.\/[^'"]+)\2/g,
    (_, start, quote, path) => `${start}${quote}${prefix}${path.slice(2)}${quote}`);
  html = html.replace(/(<script\b[^>]*type="importmap"[^>]*>)([\s\S]*?)(<\/script>)/,
    (_, start, contents, end) => {
      const map = JSON.parse(contents);
      for (const [name, value] of Object.entries(map.imports || {})) {
        if (value.startsWith('./')) map.imports[name] = prefix + value.slice(2);
      }
      return start + JSON.stringify(map) + end;
    });
  if (!/<span\b[^>]*\bid="build-version"/.test(html)) throw new Error('The page needs a visible build-version field.');
  html = html.replace(/<span\b[^>]*\bid="build-version"[^>]*>[\s\S]*?<\/span>/,
    `<span id="build-version" data-build="${release}" data-built-at="${builtAt.toISOString()}" title="Content ${release}">${buildLabel}</span>`);
  return html;
}

// Reuse the reviewed production allowlist, never the repository or its history.
execFileSync(process.execPath, [join(root, 'scripts/build-public.mjs')], { stdio: 'inherit' });
await mkdir(join(root, 'dist'), { recursive: true });
const temporary = await mkdtemp(join(root, 'dist/.pages-build-'));
try {
  const files = await collect(join(root, 'dist/panel-workbench/demo'));
  for (const file of files) if (file.relative.endsWith('.js')) file.contents = Buffer.from(versionWorkers(file.contents.toString('utf8')));
  // Include the build rules and every allowed input. A change deep in a worker
  // import or WASM dependency changes the URL of the entire runtime graph.
  // Time is deliberately excluded: identical assets remain immutable by URL.
  const hash = createHash('sha256').update(await readFile(fileURLToPath(import.meta.url)));
  for (const file of files) hash.update(`\0${file.relative}\0${file.contents.length}\0`).update(file.contents);
  const release = hash.digest('hex').slice(0, 16);
  for (const file of files) {
    const legacy = join(temporary, file.relative);
    await mkdir(dirname(legacy), { recursive: true });
    if (file.relative === 'index.html') {
      await writeFile(legacy, versionIndex(file.contents.toString('utf8'), release));
      continue;
    }
    // Root paths keep a page already open from an older deployment usable.
    // Fresh pages load exclusively from the content-addressed release below.
    await writeFile(legacy, file.contents);
    const versioned = join(temporary, 'assets', release, file.relative);
    await mkdir(dirname(versioned), { recursive: true });
    await writeFile(versioned, file.contents);
  }
  await writeFile(join(temporary, '.nojekyll'), '');
  await writeFile(join(temporary, marker), signature);
  const existing = await lstat(destination).catch(error => {
    if (error.code !== 'ENOENT') throw error;
    return null;
  });
  if (existing) {
    if (!existing.isDirectory() || existing.isSymbolicLink() ||
        await readFile(join(destination, marker), 'utf8').catch(() => '') !== signature) {
      throw new Error('The Pages destination contains an unrelated directory. Move it before rebuilding.');
    }
    await rm(destination, { recursive: true });
  }
  await rename(temporary, destination);
  console.log(`GitHub Pages files: ${destination}\n${buildLabel} · Content ${release}\nPublish this directory at the site root. No Node server is needed on the host.`);
} catch (error) {
  await rm(temporary, { recursive: true, force: true });
  throw error;
}
